-- 0001: the initial schema, docs/architecture.md § Database schema.
--
-- What the predecessor's 33 migrations learned is carried in these columns and CHECKs. Where
-- a rule was only the interface's in the predecessor, it is in the data here, so it holds
-- for every writer: the deletion window's bound, the address and login character rule,
-- the reserved logins. After the tables come the views, the grants to the roles install
-- step 6 made, and the read-back of those grants. The applier runs this file as
-- maildivvy_owner, in one transaction with its schema_version row.

-- The provider mailbox in front of a domain (the predecessor's real_mailbox).
CREATE TABLE external_mailbox (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- One character rule for the address and the POP3 login: whichever is in force is
    -- written into the fetcher's configuration as its user line.
    address             text NOT NULL CHECK (address ~ '^[^[:space:][:cntrl:]]+$'),
    address_canonical   text NOT NULL UNIQUE CHECK (address_canonical ~ '^[^[:space:][:cntrl:]]+$'),
    pop3_login          text CHECK (pop3_login ~ '^[^[:space:][:cntrl:]]+$'),
    credential          text,
    -- ⛔ A host is the provider's NAME, never an IP address: the relay checks the
    -- certificate against it, and a relay configured as an address never matches.
    -- No colon, and a last label that begins with a letter, as the host field's own
    -- HOST_ENDS_IN_A_NAME (src/maildivvy/admin/validate.py).
    pop3_host           text NOT NULL CHECK (pop3_host ~ '^[^[:space:][:cntrl:]]+$'
                                         AND pop3_host !~ ':'
                                         AND pop3_host ~ '(^|[.])[A-Za-z][^.]*$'),
    pop3_port           integer NOT NULL DEFAULT 995 CHECK (pop3_port BETWEEN 1 AND 65535),
    smtp_host           text NOT NULL CHECK (smtp_host ~ '^[^[:space:][:cntrl:]]+$'
                                         AND smtp_host !~ ':'
                                         AND smtp_host ~ '(^|[.])[A-Za-z][^.]*$'),
    smtp_port           integer NOT NULL DEFAULT 587 CHECK (smtp_port BETWEEN 1 AND 65535),
    delete_window_days  integer NOT NULL DEFAULT 14 CHECK (delete_window_days BETWEEN 1 AND 1000000),
    state               text NOT NULL DEFAULT 'deactivated' CHECK (state IN ('active', 'deactivated')),
    state_changed_at    timestamptz,
    state_changed_by    text,
    comment             text,
    last_fetch_at       timestamptz,
    last_fetch_status   text CHECK (last_fetch_status IN ('ok', 'no_new_mail', 'auth_failed', 'error')),
    last_fetch_cause    text CHECK (last_fetch_cause IN
                            ('unrecorded', 'timeout', 'stuck_message', 'unreachable', 'transient')),
    last_fetch_detail   text,
    last_test_at        timestamptz,
    last_test_status    text CHECK (last_test_status IN ('ok', 'auth_failed', 'error')),
    last_test_detail    text,
    stuck_since         timestamptz,
    stuck_runs          integer NOT NULL DEFAULT 0 CHECK (stuck_runs >= 0),
    skip_streak         integer NOT NULL DEFAULT 0 CHECK (skip_streak >= 0),
    frozen_since        timestamptz,
    last_listing_at     timestamptz,
    last_skip_at        timestamptz,
    last_skip_uidl      text,
    held_since          timestamptz
);

COMMENT ON COLUMN external_mailbox.address_canonical IS
$$The duplicate key: one provider mailbox, one row, so one fetcher.
Nothing that delivers or sends mail reads it; the sending views publish address.$$;
COMMENT ON COLUMN external_mailbox.pop3_login IS
$$The login the fetcher presents; NULL means the address as typed. It must stay
byte-equal for the life of the mailbox, or the fetcher refetches its whole window.$$;
COMMENT ON COLUMN external_mailbox.credential IS
$$Recoverable, because the relay presents it. The interface may write it and never
read it.$$;
COMMENT ON COLUMN external_mailbox.delete_window_days IS
$$Rendered as the fetcher's keep <n>d; the clock is the fetcher's first sighting. No policy
ceiling; the million-day bound keeps the date arithmetic valid.$$;
COMMENT ON COLUMN external_mailbox.last_fetch_cause IS
$$Why the last fetch was an error, from a closed list the fetch runner writes, so no
screen classifies an error from its wording.$$;
COMMENT ON COLUMN external_mailbox.held_since IS
$$When a hold began while the antivirus was unreachable; NULL when not held.$$;

-- ⛔ CHANGING A PROVIDER HOST CLEARS THE STORED PASSWORD, FOR EVERY WRITER. The interface may point a mailbox at a host of its choosing, and a fetch or a relay
-- would then present the stored provider password there, which was accepted before and
-- is narrowed here. A trigger, not the screen, enforces it, so it holds for the pipeline and
-- any future writer too. A save that leaves BOTH hosts as they were clears nothing
-- (IS DISTINCT FROM, so a NULL is compared, not lost). A mailbox with no credential is
-- neither fetched (maildivvy-credential exits 1) nor relayed (postfix_transport, the one
-- row that lets a sender send, and postfix_sasl_password both need `credential IS NOT
-- NULL`: with the transport alone gone, Postfix would still offer the message to the
-- provider, only without AUTH).
CREATE FUNCTION external_mailbox_clear_credential_on_host_change() RETURNS trigger
    LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.pop3_host IS DISTINCT FROM OLD.pop3_host
       OR NEW.smtp_host IS DISTINCT FROM OLD.smtp_host THEN
        NEW.credential := NULL;
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER external_mailbox_clear_credential_on_host_change
    BEFORE UPDATE ON external_mailbox
    FOR EACH ROW EXECUTE FUNCTION external_mailbox_clear_credential_on_host_change();

CREATE TABLE domain (
    id                    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    label                 text NOT NULL UNIQUE CHECK (label ~ '^[a-z0-9]([a-z0-9-]{0,30}[a-z0-9])?$'),
    external_mailbox_id   bigint UNIQUE REFERENCES external_mailbox (id) ON DELETE RESTRICT,
    archive_password_hash text NOT NULL CHECK (archive_password_hash LIKE '{SHA512-CRYPT}%'
                                               AND length(archive_password_hash) > length('{SHA512-CRYPT}')),
    spam_threshold        numeric(6,2) NOT NULL DEFAULT 8.00 CHECK (spam_threshold BETWEEN 1.00 AND 150.00),
    spam_reaches_people   boolean NOT NULL DEFAULT true,
    outbound_unscanned    text NOT NULL DEFAULT 'send' CHECK (outbound_unscanned IN ('send', 'refuse')),
    created_at            timestamptz NOT NULL DEFAULT now()
);

COMMENT ON COLUMN domain.spam_threshold IS
$$The score at or above which mail arriving for the domain is spam. The upper bound is
the scanner's own top score, which the product's scanner configuration sets from the
same value; if it moves, this bound moves in a migration of its own.$$;
COMMENT ON COLUMN domain.outbound_unscanned IS
$$What the milter does with outgoing mail too large to scan: send it unscanned (default)
or refuse it.$$;

-- A person. The login is the local part of every <login>@<domain> they hold.
CREATE TABLE account (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- Dots are allowed: Dovecot escapes them in folder names. `archive` is every
    -- domain's own mailbox; `break-glass` is the interface's reserved
    -- administrator.
    login         text NOT NULL UNIQUE CHECK (login ~ '^[a-z0-9]([a-z0-9._-]{0,62}[a-z0-9])?$'
                                              AND login NOT IN ('archive', 'break-glass')),
    password_hash text NOT NULL CHECK (password_hash LIKE '{SHA512-CRYPT}%'
                                       AND length(password_hash) > length('{SHA512-CRYPT}')),
    is_admin      boolean NOT NULL DEFAULT false,
    state         text NOT NULL DEFAULT 'active' CHECK (state IN ('active', 'blocked')),
    comment       text,
    created_at    timestamptz NOT NULL DEFAULT now(),
    -- ⛔ When the password last changed: a session created before it is no
    -- longer this person, so the interface's per-request read ends it. A trigger keeps it,
    -- so it holds however the hash is written, and the writer needs no privilege on it.
    password_set_at timestamptz NOT NULL DEFAULT now()
);

CREATE FUNCTION account_stamp_password_change() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.password_hash IS DISTINCT FROM OLD.password_hash THEN
        NEW.password_set_at := now();
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER account_stamp_password_change BEFORE UPDATE ON account
    FOR EACH ROW EXECUTE FUNCTION account_stamp_password_change();

-- A person's mailbox in a domain. No state and no role.
CREATE TABLE mailbox (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id bigint NOT NULL REFERENCES account (id) ON DELETE CASCADE,
    domain_id  bigint NOT NULL REFERENCES domain (id) ON DELETE RESTRICT,
    -- ⛔ clock_timestamp(), the real moment of the insert, not now(), the transaction's
    -- start: paired with message.received_at below, so a mailbox created during
    -- a pass tick is never stamped after that tick's messages while they are stamped before it.
    as_of      timestamptz NOT NULL DEFAULT clock_timestamp(),
    UNIQUE (account_id, domain_id)
);

-- The ledger's record of a message in a domain.
CREATE TABLE message (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    domain_id         bigint NOT NULL REFERENCES domain (id) ON DELETE RESTRICT,
    message_id_header text,
    archive_uid       bigint,
    state             text NOT NULL DEFAULT 'delivered' CHECK (state IN ('delivered', 'withheld', 'released')),
    withheld_id       text,
    report_of         bigint REFERENCES message (id) ON DELETE CASCADE,
    -- ⛔ clock_timestamp(), the real insert moment, not now(): the pass records
    -- many messages in one long transaction, so now() (its start) could fall BEFORE a
    -- mailbox that was created mid-tick, and the message would be missed by both the fan-out
    -- (the mailbox not yet visible) and the connect (received_at < the mailbox's as_of). The
    -- real insert time is at or after the mailbox's as_of, so the connect always catches it.
    received_at       timestamptz NOT NULL DEFAULT clock_timestamp(),
    message_date      timestamptz,
    sender            text,
    subject           text,
    is_spam           boolean NOT NULL DEFAULT false,
    spam_score        numeric(6,2)
);

COMMENT ON COLUMN message.archive_uid IS
$$The archive's UID; NULL for a message the Sent hook recorded.$$;
COMMENT ON COLUMN message.sender IS
$$The sender as parsed and lower-cased, never folded.$$;
COMMENT ON COLUMN message.is_spam IS
$$The verdict made once at delivery; NULL is never stored, a message with no score is
not spam.$$;
COMMENT ON COLUMN message.spam_score IS
$$The scanner's score; NULL when it gave none or it could not be read.$$;

-- One receiver's copy. No folder column: moves between folders are the person's own.
-- A row outliving its file is normal; a file with no row is a defect.
CREATE TABLE delivery (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    message_id bigint NOT NULL REFERENCES message (id) ON DELETE CASCADE,
    mailbox_id bigint NOT NULL REFERENCES mailbox (id) ON DELETE CASCADE,
    state      text NOT NULL DEFAULT 'pending' CHECK (state IN ('pending', 'linked')),
    linked_at  timestamptz,
    UNIQUE (message_id, mailbox_id)
);

-- The interface's queue to the pipeline. Who asked is a column, so the
-- pipeline's journal rows name them.
CREATE TABLE request (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind        text NOT NULL CHECK (kind IN (
                    'create_domain', 'create_mailbox', 'connect', 'top_up', 'deliver_one', 'release',
                    'delete_account', 'delete_mailbox', 'delete_external_mailbox', 'delete_domain',
                    'transfer', 'refetch', 'test_credential', 'activate_external_mailbox')),
    target      text,
    payload     jsonb NOT NULL DEFAULT '{}'::jsonb,
    asked_by    text NOT NULL CHECK (asked_by <> ''),
    break_glass boolean NOT NULL DEFAULT false,
    state       text NOT NULL DEFAULT 'queued' CHECK (state IN ('queued', 'running', 'done', 'failed')),
    result      text,
    created_at  timestamptz NOT NULL DEFAULT now(),
    finished_at timestamptz
);

-- The journal: append-only. request_id links the row written when an act
-- was asked for to the request that performs it.
CREATE TABLE audit (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    at          timestamptz NOT NULL DEFAULT now(),
    actor       text NOT NULL,
    action      text NOT NULL,
    target      text,
    detail      jsonb NOT NULL DEFAULT '{}'::jsonb,
    break_glass boolean NOT NULL DEFAULT false,
    request_id  bigint REFERENCES request (id)
);

CREATE FUNCTION audit_is_append_only() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION 'the journal is append-only: % on audit refused', TG_OP;
END;
$$;

CREATE TRIGGER audit_append_only BEFORE UPDATE OR DELETE OR TRUNCATE ON audit
    FOR EACH STATEMENT EXECUTE FUNCTION audit_is_append_only();

-- A signed-in session of the interface, a person's or break-glass's, never both.
CREATE TABLE session (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token_hash   text NOT NULL UNIQUE,
    account_id   bigint REFERENCES account (id) ON DELETE CASCADE,
    break_glass  boolean NOT NULL DEFAULT false,
    created_at   timestamptz NOT NULL DEFAULT now(),
    last_seen_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT session_one_holder CHECK ((account_id IS NOT NULL) <> break_glass)
);

-- ⚠️ A SESSION ROW IS REMOVED BY A FUNCTION, BECAUSE THE INTERFACE HOLDS NO DELETE.
-- The interface's role has no DELETE on any table anywhere, and a session row
-- must go at sign-out and at expiry (§ Database schema). These two functions,
-- owned by the schema owner and executed by the interface alone, are the whole of what
-- it may remove: one names a session by the hash of the token its holder presented, the
-- other takes only rows already past the two bounds. Nothing else about the row can be
-- reached through them, and no other table can. The alternative considered was a
-- `closed_at` column the lookup honours, with the pipeline reaping the rows; it was not
-- taken because it leaves the token hashes standing, spreads sign-out across two
-- programs, and contradicts "a row is deleted at sign-out and at expiry".
-- ⛔ `search_path = pg_catalog, public, pg_temp`, WITH pg_temp NAMED LAST, and every
-- table name qualified `public.<name>`. A SECURITY DEFINER function runs as
-- the owner, and pg_temp is searched BEFORE pg_catalog whenever it is not named in the
-- search_path: so `session` unqualified in a definer function resolves to the CALLER'S
-- temporary schema first. Measured on the VM (2026-09-23): as maildivvy_admin, a temp
-- `session` table with a BEFORE DELETE trigger, `GRANT ALL ON pg_temp.session TO
-- maildivvy_owner`, then `SELECT end_session('x')` ran the trigger AS maildivvy_owner and
-- read `public.external_mailbox.credential`. Naming pg_temp last puts it after public, so
-- `session` is public.session; the explicit qualification makes it so even if the setting
-- is lost. TEMPORARY is revoked from PUBLIC below, so no caller creates such a table at all.
CREATE FUNCTION end_session(p_token_hash text) RETURNS integer
    LANGUAGE sql SECURITY DEFINER SET search_path = pg_catalog, public, pg_temp AS $$
    WITH gone AS (DELETE FROM public.session WHERE token_hash = p_token_hash RETURNING 1)
    SELECT count(*)::integer FROM gone;
$$;

-- ⚠️ THE BOUNDS ARE INSIDE THE FUNCTION, NOT THE CALLER'S. They are the ones
-- fixes (15 minutes idle, 8 hours absolute), the same the interface's own
-- per-request read enforces; a caller passing its own intervals could otherwise delete
-- every session at once. The function takes no argument, so there is nothing to pass.
CREATE FUNCTION expire_sessions() RETURNS integer
    LANGUAGE sql SECURITY DEFINER SET search_path = pg_catalog, public, pg_temp AS $$
    WITH gone AS (
        DELETE FROM public.session
         WHERE last_seen_at <= now() - interval '15 minutes'
            OR created_at   <= now() - interval '8 hours'
        RETURNING 1)
    SELECT count(*)::integer FROM gone;
$$;

-- ⛔ NO CALLER MAY CREATE A TEMPORARY TABLE. With TEMPORARY revoked from
-- PUBLIC, the shadowing above cannot be set up at all; it is defence in depth beside the
-- search_path and the qualification. No consumer of this schema creates temp tables, so
-- the privilege is granted back to nobody. The owner keeps it as the database's owner.
DO $$ BEGIN
    EXECUTE format('REVOKE TEMPORARY ON DATABASE %I FROM PUBLIC', current_database());
END $$;

-- The break-glass administrator: one row. Its hash is bare, because the interface
-- verifies it and Dovecot never reads it.
CREATE TABLE break_glass (
    only_row      boolean PRIMARY KEY DEFAULT true CHECK (only_row),
    password_hash text NOT NULL CHECK (password_hash <> '' AND password_hash NOT LIKE '{%'),
    set_at        timestamptz NOT NULL DEFAULT now()
);

-- The pass's cursor per domain and archive folder: INBOX and the quarantine have their
-- own UID sequences. A writer that names no folder lands on INBOX.
CREATE TABLE pass_cursor (
    domain_id bigint NOT NULL REFERENCES domain (id) ON DELETE CASCADE,
    mailbox   text NOT NULL DEFAULT 'INBOX' CHECK (mailbox IN ('INBOX', 'Quarantine')),
    last_uid  bigint NOT NULL DEFAULT 0 CHECK (last_uid >= 0),
    PRIMARY KEY (domain_id, mailbox)
);

