-- Views (§ Views). The daemons and the milter read views, never tables. The
-- paths are store.py's derivation written out: <store>/<domain>/<account> and
-- <index>/{idx,ctl}/<domain>/<account>; test_schema_views.py holds the two
-- to each other. No uid or gid: Dovecot's mail_uid fixes them, since they
-- are an install setting and this file is not.

-- Who may open which mailbox. Dovecot's passdb and its userdb both read this one view,
-- so the rule is written once and cannot disagree with itself: the person
-- is active; the archive has no person and always opens. One lookup on the
-- whole login, never the local part alone. Both hashes are scheme-prefixed
-- and longer than the prefix, so no row answers an empty password.
CREATE VIEW mailbox_opens AS
    SELECT a.login || '@' || d.label                                AS login,
           a.password_hash                                          AS password,
           '/srv/maildivvy/store/' || d.label || '/' || a.login     AS home,
           '/srv/maildivvy/index/idx/' || d.label || '/' || a.login AS index_path,
           '/srv/maildivvy/index/ctl/' || d.label || '/' || a.login AS control_path
    FROM mailbox m
    JOIN account a ON a.id = m.account_id
    JOIN domain d ON d.id = m.domain_id
    WHERE a.state = 'active'
    UNION ALL
    SELECT 'archive@' || d.label,
           d.archive_password_hash,
           '/srv/maildivvy/store/' || d.label || '/archive',
           '/srv/maildivvy/index/idx/' || d.label || '/archive',
           '/srv/maildivvy/index/ctl/' || d.label || '/archive'
    FROM domain d;

-- Who receives in a domain: every mailbox, whatever its person's state. Blocking closes
-- the door and nothing else. The archive is where mail comes from, not a
-- receiver.
CREATE VIEW mailbox_receives AS
    SELECT m.id                                                 AS mailbox_id,
           m.domain_id,
           d.label                                              AS domain,
           a.login                                              AS account,
           a.login || '@' || d.label                            AS login,
           m.as_of,
           '/srv/maildivvy/store/' || d.label || '/' || a.login AS home
    FROM mailbox m
    JOIN account a ON a.id = m.account_id
    JOIN domain d ON d.id = m.domain_id;

-- The sending views. Only an active external mailbox sends, and each view
-- publishes the literal address as entered, never the duplicate key. A
-- login sends only while its person is active, the same rule that opens it,
-- and only in a domain with an external mailbox in front of it.

-- The milter: the address a login may send as, and what its domain does with
-- mail too large to scan.
CREATE VIEW milter_sender AS
    SELECT a.login || '@' || d.label AS login,
           e.address                 AS sender,
           d.outbound_unscanned
    FROM mailbox m
    JOIN account a ON a.id = m.account_id
    JOIN domain d ON d.id = m.domain_id
    JOIN external_mailbox e ON e.id = d.external_mailbox_id
    WHERE a.state = 'active' AND e.state = 'active';

-- ⚠️ EVERY KEY POSTFIX LOOKS A SENDER UP BY IS THE FOLDED ADDRESS, and every value is
-- the address as it was entered. Measured 2026-09-20 on 3.10.6: Postfix
-- folds a lookup key to lower case before asking a map, so an address published as it
-- was entered could never be found - a mailbox with one capital in it could not send at
-- all, and the refusal named the login (`553 ... not owned by user`). Only the CASE is
-- folded here: the dot-folded `address_canonical` is the duplicate check's, and with it
-- in a map nobody with a dotted address could send (measured on the predecessor).

-- smtpd_sender_login_maps: which login owns an envelope sender.
CREATE VIEW postfix_sender_login AS
    SELECT lower(e.address)          AS mkey,
           a.login || '@' || d.label AS mvalue
    FROM mailbox m
    JOIN account a ON a.id = m.account_id
    JOIN domain d ON d.id = m.domain_id
    JOIN external_mailbox e ON e.id = d.external_mailbox_id
    WHERE a.state = 'active' AND e.state = 'active';

-- smtp_sasl_password_maps, keyed by sender and never by host: with several mailboxes at
-- one provider, a host key authenticates as some other mailbox.
CREATE VIEW postfix_sasl_password AS
    SELECT lower(e.address)                 AS mkey,
           e.address || ':' || e.credential AS mvalue
    FROM external_mailbox e
    JOIN domain d ON d.external_mailbox_id = e.id
    WHERE e.state = 'active' AND e.credential IS NOT NULL;

-- smtp_generic_maps: the internal identity rewritten to the external address in the SMTP
-- client, after the per-sender lookups.
CREATE VIEW postfix_generic AS
    SELECT a.login || '@' || d.label AS mkey,
           e.address                 AS mvalue
    FROM mailbox m
    JOIN account a ON a.id = m.account_id
    JOIN domain d ON d.id = m.domain_id
    JOIN external_mailbox e ON e.id = d.external_mailbox_id
    WHERE a.state = 'active' AND e.state = 'active';

-- sender_dependent_default_transport_maps: only a row here lets a sender send; the
-- default and relay transports are `error`. A provider on 465 speaks TLS
-- from the first byte (RFC 8314), so it gets the `smtps` client, which is in wrapper
-- mode; the plain client there waits for a greeting that never comes. A mailbox with no
-- stored password has no row, so its mail goes to the `error` transport and is never
-- handed to the provider.
CREATE VIEW postfix_transport AS
    SELECT lower(e.address)                                         AS mkey,
           CASE WHEN e.smtp_port = 465 THEN 'smtps' ELSE 'smtp' END
               || ':[' || e.smtp_host || ']:' || e.smtp_port        AS mvalue
    FROM external_mailbox e
    JOIN domain d ON d.external_mailbox_id = e.id
    WHERE e.state = 'active' AND e.credential IS NOT NULL;

-- sender_dependent_relayhost_maps.
CREATE VIEW postfix_relayhost AS
    SELECT lower(e.address)                          AS mkey,
           '[' || e.smtp_host || ']:' || e.smtp_port AS mvalue
    FROM external_mailbox e
    JOIN domain d ON d.external_mailbox_id = e.id
    WHERE e.state = 'active';

-- ---------------------------------------------------------------------------------------
-- Grants (§ Database roles). Install step 6 makes the roles before this file runs, since
-- the owner may not create roles; each consumer has its own. A column grant is
-- written column by column, and check_grants() below reads every grant this schema
-- relies on back from the catalog.

-- Dovecot and Postfix: their views, and no table at all. The milter: one view.
GRANT SELECT ON mailbox_opens TO maildivvy_dovecot;
GRANT SELECT ON postfix_sender_login, postfix_sasl_password, postfix_generic, postfix_transport,
                postfix_relayhost TO maildivvy_postfix;
GRANT SELECT ON milter_sender TO maildivvy_milter;

-- The pipeline (fetch runner, pass, request handlers; the delivery filter holds no
-- connection and the Sent hook has a role of its own): the
-- ledger, the queue, the fetch columns, and the destruction the requests perform, files
-- first and rows second. It reads the credential: the fetcher hands it to
-- mpop through a pipe, and the password check presents it.
GRANT SELECT, DELETE ON external_mailbox TO maildivvy_pipeline;
GRANT UPDATE (state, state_changed_at, state_changed_by,
              last_fetch_at, last_fetch_status, last_fetch_cause, last_fetch_detail,
              last_test_at, last_test_status, last_test_detail,
              stuck_since, stuck_runs, skip_streak, frozen_since, last_listing_at, last_skip_at,
              last_skip_uidl, held_since)
    ON external_mailbox TO maildivvy_pipeline;
-- ⛔ NOT the archive's password hash either: every column of a domain but that.
GRANT SELECT (id, label, external_mailbox_id, spam_threshold, spam_reaches_people,
              outbound_unscanned, created_at), DELETE ON domain TO maildivvy_pipeline;
GRANT UPDATE (external_mailbox_id) ON domain TO maildivvy_pipeline;   -- unmapping first
-- ⛔ NOT the password hash: the pipeline reads a person's id and login to name
-- them, and their flag and state to re-check the last-administrator rule when it performs a
-- deletion; the hash is Dovecot's and the interface's alone.
GRANT SELECT (id, login, is_admin, state), DELETE ON account TO maildivvy_pipeline;
GRANT SELECT, INSERT, UPDATE, DELETE ON mailbox, message, delivery, pass_cursor TO maildivvy_pipeline;
GRANT SELECT, UPDATE ON request TO maildivvy_pipeline;                -- the only writer of its state
GRANT INSERT ON audit TO maildivvy_pipeline;                          -- its own rows, never RETURNING
GRANT SELECT ON mailbox_receives TO maildivvy_pipeline;

-- The Sent hook, run as vmail INSIDE EVERY IMAP PROCESS: its own least-privileged role.
-- The pipeline role reads the provider credential and deletes accounts; the
-- hook needs neither. All it does is name one sent message in the archive: read the
-- domain and the sender's mailbox, and add a `message` row and the sender's `delivery`
-- row (senthook/hook.py). No credential, no DELETE, no queue, no journal.
GRANT SELECT (id, label) ON domain TO maildivvy_senthook;
GRANT SELECT (id, account_id, domain_id) ON mailbox TO maildivvy_senthook;
GRANT SELECT (id, login) ON account TO maildivvy_senthook;
GRANT SELECT (id, domain_id, message_id_header, archive_uid), INSERT ON message TO maildivvy_senthook;
-- ⚠️ `ON CONFLICT (message_id, mailbox_id)` reads its target columns, so the insert needs
-- SELECT on those two (measured: without it, `permission denied for table delivery`)
GRANT SELECT (message_id, mailbox_id), INSERT ON delivery TO maildivvy_senthook;

-- The interface: rows, and no DELETE anywhere; every destruction is a request the
-- pipeline performs. The provider credential is written and never read back:
-- SELECT is granted column by column, every column but that one. Of the
-- fetcher's retry columns it writes only the two "resume" clears. It reads the
-- queue and the journal and never changes either. It verifies the break-glass
-- hash and never sets it.
GRANT SELECT (id, address, address_canonical, pop3_login, pop3_host, pop3_port, smtp_host, smtp_port,
              delete_window_days, state, state_changed_at, state_changed_by, comment,
              last_fetch_at, last_fetch_status, last_fetch_cause, last_fetch_detail,
              last_test_at, last_test_status, last_test_detail,
              stuck_since, stuck_runs, skip_streak, frozen_since, last_listing_at, last_skip_at,
              last_skip_uidl, held_since)
    ON external_mailbox TO maildivvy_admin;
GRANT INSERT (address, address_canonical, pop3_login, credential, pop3_host, pop3_port, smtp_host, smtp_port,
              delete_window_days, comment)
    ON external_mailbox TO maildivvy_admin;
GRANT UPDATE (address, address_canonical, pop3_login, credential, pop3_host, pop3_port, smtp_host, smtp_port,
              delete_window_days, comment, state, state_changed_at, state_changed_by,
              frozen_since, skip_streak)
    ON external_mailbox TO maildivvy_admin;
-- ⛔ UPDATE IS COLUMN BY COLUMN, NOT THE WHOLE ROW. The interface never
-- rewrites a domain's label or a person's login (an INSERT sets those once); granting it
-- UPDATE on every column let it, which the architecture does not. It writes exactly the
-- settings its screens change: the domain's policy and archive password and its one
-- mapping column, and a person's hash, flag, state and comment.
GRANT SELECT, INSERT ON domain, account TO maildivvy_admin;
GRANT UPDATE (spam_reaches_people, spam_threshold, outbound_unscanned,
              archive_password_hash, external_mailbox_id) ON domain TO maildivvy_admin;
GRANT UPDATE (password_hash, is_admin, state, comment) ON account TO maildivvy_admin;
GRANT SELECT, INSERT ON mailbox TO maildivvy_admin;
GRANT SELECT ON message, delivery, break_glass TO maildivvy_admin;
GRANT SELECT, INSERT ON request, audit TO maildivvy_admin;
GRANT SELECT, INSERT, UPDATE ON session TO maildivvy_admin;
-- and the two narrow removals of a session row, which are all the DELETE it has
REVOKE ALL ON FUNCTION end_session(text), expire_sessions() FROM PUBLIC;
GRANT EXECUTE ON FUNCTION end_session(text), expire_sessions()
    TO maildivvy_admin;

-- Health: read, no write; not the credential, the sessions or the break-glass hash.
GRANT SELECT (id, address, address_canonical, pop3_login, pop3_host, pop3_port, smtp_host, smtp_port,
              delete_window_days, state, state_changed_at, state_changed_by, comment,
              last_fetch_at, last_fetch_status, last_fetch_cause, last_fetch_detail,
              last_test_at, last_test_status, last_test_detail,
              stuck_since, stuck_runs, skip_streak, frozen_since, last_listing_at, last_skip_at,
              last_skip_uidl, held_since)
    ON external_mailbox TO maildivvy_health;
-- ⛔ NOT the password hash: health reads a person to report on them, never
-- the secret Dovecot verifies. ⛔ And only what its checks read:
-- never a message's sender or subject, the deliveries, the mailboxes, the journal, the
-- fan-out cursors or a person's comment. The store helper reads the ledger as the pipeline.
GRANT SELECT (id, login, is_admin, state, created_at) ON account TO maildivvy_health;
GRANT SELECT (id, label, external_mailbox_id, spam_threshold, spam_reaches_people,
              outbound_unscanned, created_at) ON domain TO maildivvy_health;
GRANT SELECT ON request, schema_version TO maildivvy_health;

-- ---------------------------------------------------------------------------------------
-- The grants read back. A column added to a table granted table-wide is
-- covered the moment it exists; one added to external_mailbox, granted column by column,
-- carries no privilege until named. So this asks the catalog for every grant
-- the schema relies on, including each column external_mailbox has at the time, and
-- raises naming every one that is wrong. Some clauses must come out false, above all
-- that the interface can read the credential, so a reader that answered true to
-- everything could not pass. Every later migration ends with `SELECT check_grants();`,
-- and changes this function in the same file when it changes what is relied on.
CREATE FUNCTION check_grants() RETURNS boolean LANGUAGE plpgsql AS $$
DECLARE
    wrong text[] := '{}';
    col text;
    who text;
    act text;
    rel record;
    pipeline_writes text[] := ARRAY['state', 'state_changed_at', 'state_changed_by', 'last_fetch_at',
        'last_fetch_status', 'last_fetch_cause', 'last_fetch_detail', 'last_test_at', 'last_test_status',
        'last_test_detail', 'stuck_since', 'stuck_runs', 'skip_streak', 'frozen_since', 'last_listing_at',
        'last_skip_at', 'last_skip_uidl', 'held_since'];
    admin_writes text[] := ARRAY['state', 'state_changed_at', 'state_changed_by', 'frozen_since', 'skip_streak'];
    views jsonb := '{"maildivvy_dovecot": ["mailbox_opens"],
                     "maildivvy_postfix": ["postfix_sender_login", "postfix_sasl_password", "postfix_generic",
                                           "postfix_transport", "postfix_relayhost"],
                     "maildivvy_milter": ["milter_sender"]}';
    may boolean;
BEGIN
    -- every column external_mailbox has now: the interface and health read all but the
    -- credential; the pipeline reads it all
    FOR col IN SELECT attname FROM pg_attribute
               WHERE attrelid = 'external_mailbox'::regclass AND attnum > 0 AND NOT attisdropped LOOP
        FOREACH who IN ARRAY ARRAY['maildivvy_admin', 'maildivvy_health'] LOOP
            IF has_column_privilege(who, 'external_mailbox', col, 'SELECT') <> (col <> 'credential') THEN
                wrong := wrong || format('%s %s SELECT external_mailbox.%s', who,
                                         CASE WHEN col = 'credential' THEN 'can' ELSE 'cannot' END, col);
            END IF;
        END LOOP;
        IF NOT has_column_privilege('maildivvy_pipeline', 'external_mailbox', col, 'SELECT') THEN
            wrong := wrong || format('maildivvy_pipeline cannot SELECT external_mailbox.%s', col);
        END IF;
    END LOOP;
    FOREACH act IN ARRAY ARRAY['INSERT', 'UPDATE'] LOOP
        IF NOT has_column_privilege('maildivvy_admin', 'external_mailbox', 'credential', act) THEN
            wrong := wrong || format('maildivvy_admin cannot %s external_mailbox.credential', act);
        END IF;
    END LOOP;
    -- the fetch columns are the pipeline's; the interface clears two and no counter
    FOREACH col IN ARRAY pipeline_writes LOOP
        IF NOT has_column_privilege('maildivvy_pipeline', 'external_mailbox', col, 'UPDATE') THEN
            wrong := wrong || format('maildivvy_pipeline cannot UPDATE external_mailbox.%s', col);
        END IF;
        may := col = ANY (admin_writes);
        IF has_column_privilege('maildivvy_admin', 'external_mailbox', col, 'UPDATE') <> may THEN
            wrong := wrong || format('maildivvy_admin %s UPDATE external_mailbox.%s',
                                     CASE WHEN may THEN 'cannot' ELSE 'can' END, col);
        END IF;
    END LOOP;
    FOR rel IN SELECT c.oid, c.relname FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
               WHERE n.nspname = 'public' AND c.relkind IN ('r', 'v') ORDER BY c.relname LOOP
        -- the interface deletes nothing; health writes nothing
        IF has_table_privilege('maildivvy_admin', rel.oid, 'DELETE, TRUNCATE') THEN
            wrong := wrong || format('maildivvy_admin DELETE %s', rel.relname);
        END IF;
        FOREACH act IN ARRAY ARRAY['INSERT', 'UPDATE', 'DELETE'] LOOP
            IF has_table_privilege('maildivvy_health', rel.oid, act)
                    OR (act <> 'DELETE' AND has_any_column_privilege('maildivvy_health', rel.oid, act)) THEN
                wrong := wrong || format('maildivvy_health %s %s', act, rel.relname);
            END IF;
        END LOOP;
        -- the daemons and the milter: their own views, and no table or other view
        FOR who IN SELECT jsonb_object_keys(views) LOOP
            may := (views -> who) ? rel.relname;
            IF has_any_column_privilege(who, rel.oid, 'SELECT') <> may THEN
                wrong := wrong || format('%s %s %s', who, CASE WHEN may THEN 'cannot read' ELSE 'reads' END,
                                         rel.relname);
            END IF;
            IF has_any_column_privilege(who, rel.oid, 'INSERT, UPDATE, REFERENCES')
                    OR has_table_privilege(who, rel.oid, 'DELETE, TRUNCATE, TRIGGER') THEN
                wrong := wrong || format('%s writes %s', who, rel.relname);
            END IF;
        END LOOP;
    END LOOP;
    -- the queue and the journal: the interface reads them and never changes either
    FOREACH col IN ARRAY ARRAY['request', 'audit'] LOOP
        IF NOT has_table_privilege('maildivvy_admin', col, 'SELECT') THEN
            wrong := wrong || format('maildivvy_admin cannot SELECT %s', col);
        END IF;
        IF has_table_privilege('maildivvy_admin', col, 'UPDATE') THEN
            wrong := wrong || format('maildivvy_admin UPDATE %s', col);
        END IF;
    END LOOP;
    IF NOT has_table_privilege('maildivvy_pipeline', 'mailbox_receives', 'SELECT') THEN
        wrong := wrong || 'maildivvy_pipeline cannot SELECT mailbox_receives'::text;
    END IF;
    -- the only removal the interface has: two functions of the owner's, over session
    -- rows alone, executable by the interface and by nobody else
    IF EXISTS (SELECT 1 FROM pg_proc p
                WHERE p.proname IN ('end_session', 'expire_sessions')
                  AND (NOT p.prosecdef OR p.proowner <> 'maildivvy_owner'::regrole)) THEN
        wrong := wrong || 'end_session and expire_sessions must be SECURITY DEFINER, owned by maildivvy_owner'::text;
    END IF;
    -- ⛔ the definer functions pin search_path with pg_temp LAST, or a caller's temporary
    -- schema shadows public and the function runs the caller's code as the owner
    FOR who IN SELECT proname FROM pg_proc WHERE proname IN ('end_session', 'expire_sessions') LOOP
        IF NOT EXISTS (SELECT 1 FROM pg_proc p
                        WHERE p.proname = who
                          AND 'search_path=pg_catalog, public, pg_temp' = ANY (p.proconfig)) THEN
            wrong := wrong || format('%s must SET search_path = pg_catalog, public, pg_temp', who);
        END IF;
    END LOOP;
    -- ⛔ and no caller may make such a temporary table at all
    IF has_database_privilege('public', current_database(), 'TEMP') THEN
        wrong := wrong || 'TEMPORARY on the database must be revoked from PUBLIC'::text;
    END IF;
    FOREACH act IN ARRAY ARRAY['end_session(text)', 'expire_sessions()'] LOOP
        IF NOT has_function_privilege('maildivvy_admin', act, 'EXECUTE') THEN
            wrong := wrong || format('maildivvy_admin cannot EXECUTE %s', act);
        END IF;
        FOREACH who IN ARRAY ARRAY['public', 'maildivvy_pipeline', 'maildivvy_senthook',
                                   'maildivvy_health', 'maildivvy_milter', 'maildivvy_dovecot',
                                   'maildivvy_postfix'] LOOP
            IF has_function_privilege(who, act, 'EXECUTE') THEN
                wrong := wrong || format('%s can EXECUTE %s', who, act);
            END IF;
        END LOOP;
    END LOOP;
    -- The narrowed grants. The interface writes settings, not a domain's label
    -- or a person's login; neither the pipeline nor health reads a password hash; the Sent
    -- hook has a role that only names a message.
    IF has_column_privilege('maildivvy_admin', 'domain', 'label', 'UPDATE') THEN
        wrong := wrong || 'maildivvy_admin can UPDATE domain.label'::text;
    END IF;
    IF has_column_privilege('maildivvy_admin', 'account', 'login', 'UPDATE') THEN
        wrong := wrong || 'maildivvy_admin can UPDATE account.login'::text;
    END IF;
    -- Health reads what its checks read and nothing of the mail
    FOREACH col IN ARRAY ARRAY['message', 'delivery', 'mailbox', 'audit', 'pass_cursor', 'session',
                               'break_glass'] LOOP
        IF has_any_column_privilege('maildivvy_health', col, 'SELECT') THEN
            wrong := wrong || format('maildivvy_health reads %s', col);
        END IF;
    END LOOP;
    IF has_column_privilege('maildivvy_health', 'account', 'comment', 'SELECT') THEN
        wrong := wrong || 'maildivvy_health can SELECT account.comment'::text;
    END IF;
    IF NOT (has_table_privilege('maildivvy_health', 'request', 'SELECT')
            AND has_table_privilege('maildivvy_health', 'schema_version', 'SELECT')
            AND has_column_privilege('maildivvy_health', 'domain', 'label', 'SELECT')
            AND has_column_privilege('maildivvy_health', 'domain', 'external_mailbox_id', 'SELECT')) THEN
        wrong := wrong || 'maildivvy_health must read request, schema_version, domain.label and domain.external_mailbox_id'::text;
    END IF;
    FOREACH who IN ARRAY ARRAY['maildivvy_pipeline', 'maildivvy_health'] LOOP
        IF has_column_privilege(who, 'account', 'password_hash', 'SELECT') THEN
            wrong := wrong || format('%s can SELECT account.password_hash', who);
        END IF;
        IF has_column_privilege(who, 'domain', 'archive_password_hash', 'SELECT') THEN
            wrong := wrong || format('%s can SELECT domain.archive_password_hash', who);
        END IF;
    END LOOP;
    IF NOT (has_column_privilege('maildivvy_senthook', 'domain', 'label', 'SELECT')
            AND has_column_privilege('maildivvy_senthook', 'account', 'login', 'SELECT')
            AND has_column_privilege('maildivvy_senthook', 'mailbox', 'id', 'SELECT')
            AND has_table_privilege('maildivvy_senthook', 'message', 'INSERT')
            AND has_column_privilege('maildivvy_senthook', 'message', 'id', 'SELECT')
            AND has_table_privilege('maildivvy_senthook', 'delivery', 'INSERT')
            AND has_column_privilege('maildivvy_senthook', 'delivery', 'message_id', 'SELECT')) THEN
        wrong := wrong || 'maildivvy_senthook must read domain/account/mailbox and INSERT message and delivery'::text;
    END IF;
    IF has_any_column_privilege('maildivvy_senthook', 'external_mailbox'::regclass, 'SELECT, INSERT, UPDATE')
       OR has_column_privilege('maildivvy_senthook', 'account', 'password_hash', 'SELECT')
       OR has_table_privilege('maildivvy_senthook', 'account', 'DELETE')
       OR has_table_privilege('maildivvy_senthook', 'request', 'SELECT, INSERT')
       OR has_table_privilege('maildivvy_senthook', 'audit', 'INSERT') THEN
        wrong := wrong || 'maildivvy_senthook must not touch the credential, the hash, DELETE, or the queue and journal'::text;
    END IF;

    IF cardinality(wrong) > 0 THEN
        RAISE EXCEPTION 'the grants the schema relies on do not hold: %', array_to_string(wrong, '; ')
            USING HINT = 'grant or revoke in the migration that changed them; on external_mailbox, column by column';
    END IF;
    RETURN true;
END;
$$;

REVOKE ALL ON FUNCTION check_grants() FROM PUBLIC;

SELECT check_grants();
